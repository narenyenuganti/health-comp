#!/usr/bin/env bash
# Saves every database function the app can call into a database test, so a
# later migration that breaks a build people have installed fails Backend CI.
# The list is saved from the newest release and still covers older builds,
# because a function stays listed until its line is deleted. Run this at each
# release, against a freshly reset local database:
#
#   supabase db reset
#   HEALTHCOMP_TEST_DATABASE_URL=postgresql://... \
#     bash scripts/save-released-api.sh "1.0.4 (4)"

set -euo pipefail

build="${1:?Usage: save-released-api.sh \"<version> (<build>)\"}"
: "${HEALTHCOMP_TEST_DATABASE_URL:?Set HEALTHCOMP_TEST_DATABASE_URL to the local database.}"
if [[ ! "$build" =~ ^[0-9.]+\ \([0-9]+\)$ ]]; then
  echo "Name the build like: 1.0.4 (4)" >&2
  exit 1
fi

cd "$(git rev-parse --show-toplevel)"
test_file=supabase/tests/900_released_api.test.sql

# Save only from HealthComp with exactly this checkout's migrations applied.
applied="$(psql -XqAt "$HEALTHCOMP_TEST_DATABASE_URL" --command="
  select string_agg(version, ' ' order by version)
  from supabase_migrations.schema_migrations" 2>/dev/null || true)"
expected="$(ls supabase/migrations/*.sql | sed -E 's#.*/([0-9]+)_.*#\1#' | sort | paste -sd ' ' -)"
if [[ "$applied" != "$expected" ]]; then
  echo "The database is not HealthComp at this checkout's migrations; run supabase db reset first." >&2
  exit 1
fi

# One row per function the signed-in or signed-out app can call.
# ponytail: results compare as text, so adding a column to a function that
# returns a table reads as a change. No function returns a table today; compare
# returned columns one by one if that changes.
callable="
    select p.proname::text as fn,
           pg_get_function_result(p.oid) as returns,
           coalesce(array_agg(a.arg order by a.n) filter (where a.n is not null), '{}') as args,
           coalesce(array_agg(a.arg order by a.n)
             filter (where a.n <= p.pronargs - p.pronargdefaults), '{}') as required
    from pg_proc p
    left join lateral (
      select coalesce(u.name, '') || ' ' || format_type(u.type, null) as arg,
             row_number() over (order by u.ord) as n
      from unnest(
        coalesce(p.proallargtypes, p.proargtypes::oid[]), p.proargmodes, p.proargnames
      ) with ordinality as u(type, mode, name, ord)
      where coalesce(u.mode, 'i') in ('i', 'b', 'v')
    ) a on true
    where p.pronamespace = 'public'::regnamespace and p.prokind = 'f'
      and (has_function_privilege('authenticated', p.oid, 'execute')
        or has_function_privilege('anon', p.oid, 'execute'))
    group by p.oid"

released="$(psql -XqAt --set=ON_ERROR_STOP=1 "$HEALTHCOMP_TEST_DATABASE_URL" --command="
  select string_agg(
    format('    (%L, %L, %L::text[], %L::text[])', fn, returns, args, required),
    E',\n' order by fn, args)
  from ($callable) callable")"
if [[ -z "$released" ]]; then
  echo "The database has no callable functions; reset it first." >&2
  exit 1
fi

cat >"$test_file" <<SQL
-- Generated by scripts/save-released-api.sh for build $build.
-- Run the script again at each release. Delete a line by hand only to retire
-- a function that no installed build calls any more.
begin;

set local role postgres;
create extension if not exists pgtap with schema extensions;
set local search_path = extensions, public, pg_catalog;

select plan(1);

-- A released call still works when a function of the same name and result
-- accepts every argument the build could send and requires nothing new.
select is_empty(\$released\$
  with callable as ($callable
  ),
  released(fn, returns, args, required) as (values
$released
  )
  select r.fn, r.args from released r
  where not exists (
    select 1 from callable c
    where c.fn = r.fn and c.returns = r.returns
      and r.args <@ c.args and c.required <@ r.required
  )
  -- PostgREST picks an overload by argument names alone and fails the call
  -- (PGRST203) when two of them accept the names the build sends.
  or (select count(*) from callable c
      where c.fn = r.fn
        and array(select split_part(x, ' ', 1) from unnest(r.args) x)
          <@ array(select split_part(x, ' ', 1) from unnest(c.args) x)
        and array(select split_part(x, ' ', 1) from unnest(c.required) x)
          <@ array(select split_part(x, ' ', 1) from unnest(r.args) x)) <> 1
\$released\$,
  'builds up to $build can still call every function they shipped with; if not, keep the old function and add the change as optional arguments or a new overload');

select * from finish();
rollback;
SQL
echo "Saved $(grep -c '^    (' "$test_file") functions for build $build in $test_file."
