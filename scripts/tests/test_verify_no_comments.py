import importlib.util
from pathlib import Path
import tempfile
import unittest


SCRIPT_PATH = Path(__file__).resolve().parent.parent / "verify-no-comments.py"
SPEC = importlib.util.spec_from_file_location("verify_no_comments", SCRIPT_PATH)
assert SPEC is not None and SPEC.loader is not None
MOD = importlib.util.module_from_spec(SPEC)
import sys
sys.modules["verify_no_comments"] = MOD
SPEC.loader.exec_module(MOD)


class CommentLexerTests(unittest.TestCase):
    def test_swift_ignores_urls_raw_strings_and_interpolations(self):
        source = '''
let url = "https://example.com//not-a-comment"
let raw = #"/* still not a comment */ // neither"#
let nested = "prefix \\("inner // not a comment") suffix /* also not */"
let real = 1 // actual comment
'''
        lines = MOD.comment_line_numbers("App.swift", source)
        self.assertEqual(lines, [5])

    def test_swift_nested_block_comments(self):
        source = """
/* outer
   /* inner */
   still outer */
let ok = true
"""
        lines = MOD.comment_line_numbers("Nested.swift", source)
        self.assertEqual(lines, [2, 3, 4])

    def test_swift_package_tools_version_is_exempt(self):
        source = "// swift-tools-version: 5.9\nimport PackageDescription\n"
        self.assertEqual(
            MOD.comment_line_numbers("Modules/CompetitionCore/Package.swift", source),
            [],
        )

    def test_js_ignores_regex_and_template_literals(self):
        source = r"""
const email = /^[^@\s]+@[^@\s]+\.[^@\s]+$/;
const url = `https://api.example.com/${"a // b"}`;
const a = 10 / 2;
const b = 1; // real comment
"""
        lines = MOD.comment_line_numbers("index.ts", source)
        self.assertEqual(lines, [5])

    def test_js_exempts_deno_lint_ignore(self):
        source = "// deno-lint-ignore-file require-await\nexport const x = 1;\n"
        self.assertEqual(MOD.comment_line_numbers("test.ts", source), [])

    def test_sql_ignores_strings_and_catches_plpgsql_comments(self):
        source = """
select '-- not a comment' as txt;
create function f() returns void language plpgsql as $$
begin
  -- real plpgsql comment
  return;
end;
$$;
"""
        lines = MOD.comment_line_numbers("fn.sql", source)
        self.assertEqual(lines, [5])

    def test_released_api_header_is_exempt(self):
        for header in (
            "-- Callable catalogue for build 1.0.7 (7).\nselect 1;\n",
            "-- Generated by scripts/save-released-api.sh for build 1.0.8 (8).\nselect 1;\n",
        ):
            self.assertEqual(
                MOD.comment_line_numbers("supabase/tests/900_released_api.test.sql", header),
                [],
            )

    def test_shell_ignores_shebang_heredoc_and_param_length(self):
        source = """#!/usr/bin/env bash
set -euo pipefail
count="${#args[@]}"
cat >out.xcconfig <<'EOF'
#include "Base.xcconfig"
#include? "Local.xcconfig"
EOF
echo "https://example.com/#frag"
# real shell comment
"""
        lines = MOD.comment_line_numbers("scripts/check.sh", source)
        self.assertEqual(lines, [9])

    def test_python_ignores_shebang_and_strings(self):
        source = '#!/usr/bin/env python3\ns = "# not a comment"\nx = 1  # real\n'
        self.assertEqual(MOD.comment_line_numbers("scripts/tool.py", source), [3])


class RatchetEnforcementTests(unittest.TestCase):
    def test_ratchet_blocks_new_comments_and_requires_tightening(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            ratchet = root / "scripts" / "comment-ratchet.json"
            ratchet.parent.mkdir(parents=True)
            legacy = root / "legacy.swift"
            legacy.write_text("// one\n// two\nlet x = 1\n", encoding="utf-8")

            self.assertEqual(
                MOD.main(["--root", str(root), "--ratchet", str(ratchet), "--init-ratchet"]),
                0,
            )
            self.assertEqual(
                MOD.main(["--root", str(root), "--ratchet", str(ratchet)]),
                0,
            )

            clean_new = root / "new.swift"
            clean_new.write_text("// banned\nlet y = 2\n", encoding="utf-8")
            self.assertEqual(
                MOD.main(["--root", str(root), "--ratchet", str(ratchet)]),
                1,
            )
            self.assertEqual(
                MOD.main(["--root", str(root), "--ratchet", str(ratchet), "--update-ratchet"]),
                1,
            )
            clean_new.unlink()

            legacy.write_text("// one\n// two\n// three\nlet x = 1\n", encoding="utf-8")
            self.assertEqual(
                MOD.main(["--root", str(root), "--ratchet", str(ratchet)]),
                1,
            )

            legacy.write_text("// one\nlet x = 1\n", encoding="utf-8")
            self.assertEqual(
                MOD.main(["--root", str(root), "--ratchet", str(ratchet)]),
                1,
            )
            self.assertEqual(
                MOD.main(["--root", str(root), "--ratchet", str(ratchet), "--update-ratchet"]),
                0,
            )
            self.assertEqual(
                MOD.main(["--root", str(root), "--ratchet", str(ratchet)]),
                0,
            )

            legacy.write_text("let x = 1\n", encoding="utf-8")
            self.assertEqual(
                MOD.main(["--root", str(root), "--ratchet", str(ratchet), "--update-ratchet"]),
                0,
            )
            self.assertEqual(MOD.load_ratchet(ratchet), {})
            self.assertEqual(
                MOD.main(["--root", str(root), "--ratchet", str(ratchet)]),
                0,
            )


if __name__ == "__main__":
    unittest.main()
